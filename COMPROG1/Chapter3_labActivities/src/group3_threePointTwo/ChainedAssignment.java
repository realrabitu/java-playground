package group3_threePointTwo;

public class ChainedAssignment {

	public static void main(String[] args) {
		int a, b, c;
		a = b = c = 100; // assigning values at the same line
		System.out.println("Value of a: " + a); // 100
		System.out.println("Value of b: " + b); // 100
		System.out.println("Value of c: " + c); // 100
		

	}

}
